create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'client' check (role in ('admin','staff','client')),
  full_name text,
  phone text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.customers (
  id uuid primary key default gen_random_uuid(),
  full_name text not null,
  document_number text,
  phone text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists customers_full_name_idx on public.customers using gin (full_name gin_trgm_ops);

create table if not exists public.lockers (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.cash_registers (
  id uuid primary key default gen_random_uuid(),
  opened_by uuid references public.profiles(id),
  closed_by uuid references public.profiles(id),
  opening_amount numeric(10,2) not null default 0,
  opened_at timestamptz not null default now(),
  closed_at timestamptz,
  status text not null default 'open' check (status in ('open','closed')),
  total_cash numeric(10,2) not null default 0,
  total_qr numeric(10,2) not null default 0,
  total_transfer numeric(10,2) not null default 0,
  total_other_income numeric(10,2) not null default 0,
  total_expenses numeric(10,2) not null default 0,
  closing_balance numeric(10,2) not null default 0,
  notes text
);

create table if not exists public.sales (
  id uuid primary key default gen_random_uuid(),
  sale_number bigint generated by default as identity,
  customer_id uuid references public.customers(id),
  user_id uuid references public.profiles(id),
  cash_register_id uuid references public.cash_registers(id),
  sale_type text not null check (sale_type in ('locker','no_locker')),
  quantity int not null default 1,
  unit_price numeric(10,2) not null,
  subtotal numeric(10,2) not null,
  discount_percentage numeric(5,2) not null default 0,
  discount_amount numeric(10,2) not null default 0,
  total numeric(10,2) not null,
  payment_method text not null check (payment_method in ('cash','qr','transfer')),
  created_at timestamptz not null default now()
);
create unique index if not exists sales_sale_number_uidx on public.sales(sale_number);

create table if not exists public.sale_lockers (
  id uuid primary key default gen_random_uuid(),
  sale_id uuid not null references public.sales(id) on delete cascade,
  locker_id uuid not null references public.lockers(id),
  released_at timestamptz,
  created_at timestamptz not null default now()
);
-- Un casillero solo puede tener UNA fila "activa" (sin liberar) a la vez.
-- Esto es lo que impide vender el mismo casillero a dos clientes al mismo tiempo.
create unique index if not exists sale_lockers_active_locker_uidx
  on public.sale_lockers(locker_id) where released_at is null;

create table if not exists public.cash_movements (
  id uuid primary key default gen_random_uuid(),
  cash_register_id uuid not null references public.cash_registers(id) on delete cascade,
  type text not null check (type in ('income','expense')),
  concept text not null,
  amount numeric(10,2) not null,
  user_id uuid references public.profiles(id),
  created_at timestamptz not null default now()
);

create table if not exists public.business_settings (
  id int primary key default 1,
  business_name text not null default 'El Paraíso',
  logo_url text,
  address text,
  phone text,
  email text,
  locker_price numeric(10,2) not null default 20,
  no_locker_price numeric(10,2) not null default 15,
  discount_enabled boolean not null default true,
  discount_default_percentage numeric(5,2) not null default 10,
  updated_at timestamptz not null default now(),
  constraint business_settings_single_row check (id = 1)
);

insert into public.business_settings (id) values (1)
  on conflict (id) do nothing;

