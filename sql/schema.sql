-- =====================================================================
-- 3) FUNCIÓN AUXILIAR: obtener el rol del usuario que está conectado
-- =====================================================================
create or replace function public.get_my_role()
returns text
language sql
security definer
stable
set search_path = public
as $$
  select role from public.profiles where id = auth.uid();
$$;


-- =====================================================================
-- 4) TRIGGER: al registrarse un usuario nuevo, crear su perfil
--    automáticamente con role = 'client'
-- =====================================================================
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, role, full_name)
  values (new.id, 'client', coalesce(new.raw_user_meta_data->>'full_name', new.email))
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- Trigger de seguridad: un usuario normal no puede cambiarse su propio rol.
-- Solo un administrador puede modificar el rol de cualquier perfil.
create or replace function public.prevent_role_self_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  -- auth.uid() es NULL cuando el cambio se hace desde el SQL Editor de Supabase
  -- (por ejemplo, al configurar el primer administrador). En ese caso se permite.
  -- Cuando el cambio viene de la aplicación (usuario autenticado), solo un
  -- administrador puede modificar el rol de un perfil.
  if new.role is distinct from old.role and auth.uid() is not null and public.get_my_role() is distinct from 'admin' then
    raise exception 'No tienes permiso para cambiar el rol de este usuario.';
  end if;
  return new;
end;
$$;

drop trigger if exists on_profiles_role_change on public.profiles;
create trigger on_profiles_role_change
  before update on public.profiles
  for each row execute procedure public.prevent_role_self_change();


