-- =====================================================================
-- 6) CREAR AL PRIMER ADMINISTRADOR
--    ⬇️  CAMBIA el correo de la línea siguiente por el que usaste al
--    crear el usuario en Authentication → Users → Add user.
-- =====================================================================
do $$
declare
  admin_email text := 'admin@elparaiso.com';  -- <--- CAMBIA ESTE CORREO
  admin_id uuid;
begin
  select id into admin_id from auth.users where email = admin_email;

  if admin_id is null then
    raise notice 'No se encontró ningún usuario con el correo %. Créalo primero en Authentication → Users → Add user, y luego vuelve a ejecutar este bloque.', admin_email;
  else
    insert into public.profiles (id, role, full_name)
    values (admin_id, 'admin', 'Administrador')
    on conflict (id) do update set role = 'admin';
    raise notice 'Usuario % configurado como administrador correctamente.', admin_email;
  end if;
end $$;

